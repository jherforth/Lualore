if SPAWNING then
	mobs:spawn({
		name = "lualore:mirror_sentinel",
		-- any natural floatland surface: Asuna puts every surface biome up
		-- there, so the island tops vary as much as the ground does
		nodes = {
			"group:crumbly", "group:stone", "group:sand",
			"everness:dirt_with_crystal_grass",
		},
		neighbors = {"air"},
		min_light = 0,
		max_light = 15,
		interval = 30,
		chance = 9000,
		active_object_count = 2,
