--[[
	The Mirror Sentinel - a wandering enemy of the sky islands.

	It used to be the boss of the obsidian door trials, guarding a mirror
	door on a floating island with 220-260 HP. The doors are gone (sky
	portals replace them, see portal/SKY_PORTAL.md) and the Sentinel is now
	an ordinary hostile that spawns on the floatlands: tougher than a Lit,
	well short of a valkyrie.

	It hovers. Left alone it drifts around the spot it spawned at rather
	than out over the void; in a fight it keeps its distance and casts the
	black wizard's blindness curse (lualore.wizard_magic.black_do_custom,
	one spell every four seconds at most).

	It drops mese - fragments, sometimes a whole crystal - which is what a
	portal frame is made of, so hunting them up there pays for the next
	portal down here.

	The model is models/mirror_sentinel.gltf, generated by
	tools/make_mirror_sentinel.py; it does not use character.b3d.
]]

local S = minetest.get_translator("lualore")

local SKY_Y = math.floor(tonumber(
	minetest.settings:get("lualore_portal_sky_y")) or 290)
local SPAWNING = minetest.settings:get_bool("lualore_mirror_sentinels", true)

-- How far it drifts from where it spawned before turning back.
local HOME_RADIUS = 20

local function sentinel_do_custom(self, dtime)
	if not self.object then
		return
	end
	local pos = self.object:get_pos()
	if not pos then
		return
	end
	if not self.home_pos then
		self.home_pos = vector.round(pos)
	end

	if self.attack and self.state == "attack" then
		-- keep to spell range: back off when crowded, close in when far
		local target = self.attack:get_pos()
		if target then
			local dist = vector.distance(pos, target)
			local dir = vector.direction(pos, target)
			if dist < 3.0 then
				self.object:set_velocity(vector.multiply(dir, -2.0))
			elseif dist > 14.0 then
				self.object:set_velocity(vector.multiply(dir, 2.0))
			end
		end
	elseif vector.distance(pos, self.home_pos) > HOME_RADIUS then
		local dir = vector.direction(pos, self.home_pos)
		self.object:set_velocity(vector.multiply(dir, 1.4))
	end

	if lualore.wizard_magic and lualore.wizard_magic.black_do_custom then
		pcall(lualore.wizard_magic.black_do_custom, self, dtime)
	end
end

